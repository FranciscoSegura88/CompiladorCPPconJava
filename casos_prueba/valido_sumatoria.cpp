#include <iostream>
using namespace std;

class Sumatoria {
public:
    int main() {
        cout << "Segura Valencia Francisco";

        int n = 10;
        int suma = 0;
        int i = 1;

        for (i = 1; i <= n; i++) {
            suma = suma + i;
        }

        cout << suma;

        return 0;
    }
};